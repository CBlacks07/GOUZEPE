      <div class="card legal-card">
        <h2>Préambule</h2>
        <p>
          Le GOUZEPE Gaming Club (ci-après « le Club »), conformément à ses statuts, a pour mission de
          rassembler les passionnés de jeux vidéo dans un cadre compétitif, ludique et convivial entre ses
          membres.
        </p>
        <p>
          Le championnat eFootball a pour objet de fixer les règles officielles, les procédures et les
          modalités de déroulement de la compétition pour chaque saison, en complément et en précision des
          dispositions générales contenues dans les statuts du Club, auxquels il reste subordonné.
        </p>
        <p>
          Toute inscription et participation au championnat eFootball emporte l'adhésion sans réserve du
          joueur aux présents articles ainsi qu'aux statuts du Club. Nul ne pourra se prévaloir de son
          ignorance de ce règlement.
        </p>
        <p>Les objectifs primordiaux du championnat sont :</p>
        <ul class="legal-list">
          <li>Garantir une compétition équitable et une organisation irréprochable des journées, du calcul des classements et de l'attribution des titres et récompenses.</li>
          <li>Maintenir et renforcer une ambiance de camaraderie, de respect et d'entraide entre les membres.</li>
          <li>Offrir un cadre compétitif, équitable et structuré à tous les membres désireux de mesurer leur talent.</li>
        </ul>
        <p>
          <strong>Procédure de lancement :</strong> la saison débute officiellement deux (2) à trois (3)
          semaines après l'officialisation de la sortie mondiale d'une nouvelle version du jeu, afin de
          permettre à tous les membres de se familiariser avec les nouvelles mécaniques de jeu.
        </p>
        <p>
          <strong>Procédure de clôture :</strong> la saison prend fin officiellement à la veille de la sortie
          de la version suivante.
        </p>

        <h2>A1 — Principe du Championnat et de la Saison</h2>
        <h3>1.1 Durée d'une saison</h3>
        <p>
          Une saison compétitive du GOUZEPE Gaming Club correspond à la durée de vie commerciale d'une
          version annuelle du jeu eFootball (ou toute autre chronologie fixée par le Bureau Exécutif).
        </p>
        <h3>1.2 Organisation d'une journée de Championnat</h3>
        <ul class="legal-list">
          <li><strong>Fréquence :</strong> sauf cas exceptionnel (jour férié majeur, événement spécial du Club, etc.), chaque journée se joue sous forme de mini-championnat en « round-robin » au sein de chaque division — chaque joueur affronte tous les autres joueurs de sa division au cours de la journée.</li>
          <li><strong>Calendrier :</strong> le calendrier de la journée est communiqué par le Comité d'Organisation (groupe WhatsApp) aux joueurs au moins 24 heures avant le début de la journée.</li>
        </ul>
        <p class="legal-example">
          Exemple : une division composée de 6 joueurs (A, B, C, D, E, F) — au cours de la journée, le joueur
          A affronte B, C, D, E et F. Le calendrier précis des confrontations est déterminé au moins 24 heures
          à l'avance.
        </p>
        <h3>1.3 Objectif final</h3>
        <ul class="legal-list">
          <li><strong>Objectif hebdomadaire :</strong> réaliser la meilleure performance possible lors de chaque journée pour gagner une promotion ou éviter la relégation.</li>
          <li><strong>Objectif saisonnier :</strong> accumuler le plus grand nombre de points au Classement Général. Le joueur totalisant le plus de points à l'issue de la dernière journée est sacré Champion de la Saison du GOUZEPE Gaming Club.</li>
        </ul>

        <h2>A2 — Structure des Divisions et Classements</h2>
        <h3>2.1 Les Divisions</h3>
        <ul class="legal-list">
          <li><strong>Division 1 (D1) :</strong> regroupe les meilleurs joueurs du Club, l'élite du championnat. La compétition y est la plus relevée — c'est la « vitrine » de l'excellence compétitive du Club.</li>
          <li><strong>Division 2 (D2) :</strong> l'antichambre de l'élite. Elle permet aux nouveaux membres, aux joueurs en progression et à ceux relégués de D1 de se confronter et de gagner leur place en Division 1.</li>
        </ul>
        <h3>2.2 Le Classement de la Journée et ses critères de départage</h3>
        <p>
          À l'issue de chaque journée, un classement spécifique à cette journée est établi pour chaque
          division. Il détermine les promotions et relégations (voir A3) et sert de base à l'attribution des
          points du Classement Général.
        </p>
        <p><strong>Points par match :</strong> Victoire = 3 points · Match nul = 1 point · Défaite = 0 point.</p>
        <h3>2.3 Le Classement Général de la Saison</h3>
        <p>
          Le Classement Général est le classement principal qui détermine le Champion de la Saison — il
          cumule, journée après journée, les points attribués selon le classement du jour dans chaque
          division. Le système est conçu pour valoriser fortement la performance en Division 1 : un joueur
          bien classé en D1 gagne significativement plus de points qu'un joueur bien classé en D2
          (voir <a href="#annexe-1">Annexe 1</a>).
        </p>

        <h2>A3 — Promotions, Relégations et Gestion des Invités</h2>
        <h3>3.1 Principe général</h3>
        <p>
          À l'issue de chaque journée de championnat, les divisions sont réajustées. Ce système assure une
          mobilité constante entre les divisions et récompense la performance immédiate tout en sanctionnant
          la contre-performance.
        </p>
        <h3>3.2 Constitution initiale des divisions en début de saison</h3>
        <p>
          En tout début de saison, la composition initiale des divisions est établie par le Bureau Exécutif,
          sur la base du classement de la saison précédente et de l'intégration des nouveaux membres.
        </p>
        <h3>3.3 Statut et règles spécifiques applicables aux invités</h3>
        <p>
          Le Club peut autoriser la participation ponctuelle de joueurs non-membres (« invités ») à une ou
          plusieurs journées, afin de leur faire découvrir l'ambiance du championnat. Cette participation est
          strictement encadrée :
        </p>
        <ul class="legal-list">
          <li>Un invité commence systématiquement en Division 2, quel que soit son niveau ou sa réputation.</li>
          <li>Un invité, même classé premier de sa division, n'a pas droit au titre de « Champion de la journée » ni aux points correspondants du Classement Général.</li>
          <li>Le nombre d'invités par journée peut être limité par le Comité d'Organisation afin de garantir la place aux membres.</li>
          <li><strong>Procédure d'invitation :</strong> un membre du Club souhaitant inviter un joueur doit notifier le Comité d'Organisation, qui approuve ou non la demande.</li>
        </ul>
        <h3>3.4 Promotion et relégation directes</h3>
        <ul class="legal-list">
          <li><strong>Promotion directe en Division 1 :</strong> le joueur qui termine premier du classement de la Division 2 est automatiquement promu en Division 1 pour la journée suivante.</li>
          <li><strong>Relégation directe en Division 2 :</strong> le joueur qui termine dernier du classement de la Division 1 est automatiquement relégué en Division 2 pour la journée suivante.</li>
        </ul>
        <h3>3.5 Organisation des barrages de maintien/promotion</h3>
        <p>Un match de barrage est organisé pour déterminer le dernier participant de la Division 1 pour la semaine suivante.</p>
        <ul class="legal-list">
          <li><strong>Opposition :</strong> le barrage oppose l'avant-dernier de la Division 1 au deuxième de la Division 2.</li>
          <li><strong>Format :</strong> le premier joueur à remporter deux matchs gagne sa place en Division 1 pour la semaine suivante.</li>
        </ul>
        <h3>3.6 Gestion des absences prolongées</h3>
        <p>
          Tout membre de Division 1 qui enregistre cinq (5) absences cumulées ou trois (3) absences
          consécutives est automatiquement relégué en Division 2 à son retour. Cette mesure vise à ne pas
          fausser le classement par l'absence prolongée d'un joueur ; sa gestion relève de la responsabilité
          administrative du Comité d'Organisation.
        </p>

        <h2>A4 — Déroulement des Journées, Ponctualité et Sanctions</h2>
        <h3>4.1 Horaire officiel et ponctualité</h3>
        <ul class="legal-list">
          <li><strong>Heure de convocation :</strong> tous les joueurs sont tenus d'être présents (physiquement ou en salon en ligne) à l'heure de convocation, pour l'enregistrement final et le briefing d'avant-journée.</li>
          <li><strong>Heure de début des matchs :</strong> le premier match de la journée doit être lancé à l'heure prévue.</li>
          <li><strong>Marge de tolérance :</strong> aucune marge de tolérance n'est accordée à cette heure.</li>
        </ul>
        <h3>4.2 Enregistrement obligatoire des matchs</h3>
        <p>
          Pour des raisons de transparence, de résolution de litiges et de promotion du Club, l'enregistrement
          vidéo des matchs est obligatoire.
        </p>
        <ul class="legal-list">
          <li><strong>Obligation :</strong> tous les matchs de championnat doivent être intégralement enregistrés par l'un des deux joueurs.</li>
          <li><strong>Responsabilité :</strong> chaque joueur est responsable de l'enregistrement de ses propres matchs via la fonction de capture intégrée à la console.</li>
          <li><strong>Utilisation :</strong> les enregistrements servent à la résolution des litiges et à la promotion du Club (résumés de journée, etc.).</li>
        </ul>
        <h3>4.3 Procédure en cas d'arrivée tardive</h3>
