        <h2>A5 — Forfaits et Abandons</h2>
        <h3>5.1 Forfait partiel (autorisé)</h3>
        <p>
          Un forfait partiel se produit lorsqu'un joueur, déjà présent et ayant commencé sa journée, se
          trouve dans l'incapacité de terminer l'ensemble de ses matchs restants.
        </p>
        <ul class="legal-list">
          <li><strong>Condition :</strong> le forfait partiel n'est autorisé que si le joueur en informe un membre du Comité d'Organisation.</li>
          <li><strong>Conséquence :</strong> les matchs restants sont considérés comme perdus par forfait ; seuls les matchs déjà joués sont conservés au classement.</li>
        </ul>
        <h3>5.2 Abandon majeur (non autorisé)</h3>
        <p>
          Un abandon majeur — abandon volontaire et unilatéral du championnat en cours de journée — est
          considéré comme un manque de respect grave envers l'organisation et les autres participants.
          Sanctions :
        </p>
        <ol class="legal-list legal-list--num">
          <li><strong>Annulation des résultats du jour :</strong> tous les résultats du joueur pour la journée en cours sont annulés, comme si les matchs n'avaient jamais été joués.</li>
          <li><strong>Suspension :</strong> le joueur peut être suspendu, dans l'attente d'une décision du Bureau Exécutif.</li>
          <li><strong>Sanction financière :</strong> un montant peut être fixé par le Bureau Exécutif selon la gravité des circonstances.</li>
        </ol>
        <h3>5.3 Attribution des points en cas de forfait</h3>
        <ul class="legal-list">
          <li><strong>Score officiel :</strong> 3-0 en faveur du vainqueur.</li>
          <li><strong>Points :</strong> le vainqueur reçoit les points de la victoire.</li>
          <li><strong>Goal-average :</strong> les buts d'un match gagné par forfait ne comptent ni en positif pour le vainqueur, ni en négatif pour le perdant, dans le calcul du goal-average.</li>
        </ul>

        <h2>A6 — Paramètres de Match et Fair-Play</h2>
        <h3>6.1 Paramètres officiels des matchs</h3>
        <ul class="legal-list legal-list--params">
          <li><strong>Mode de jeu :</strong> Match Authentique</li>
          <li><strong>Durée du match :</strong> 10 minutes</li>
          <li><strong>Prolongations :</strong> Non (sauf match de barrage décisif)</li>
          <li><strong>Tirs au but :</strong> Non (sauf match de barrage décisif)</li>
          <li><strong>Niveau de difficulté :</strong> Super Star</li>
          <li><strong>Condition des joueurs :</strong> Normale (flèches jaunes)</li>
          <li><strong>Météo :</strong> Ensoleillé</li>
          <li><strong>Heure :</strong> Nuit</li>
          <li><strong>Stade :</strong> eFootball Stadium</li>
        </ul>
        <h3>6.2 Choix et déclaration des équipes</h3>
        <p>Chaque joueur est libre d'utiliser un maximum de deux (2) équipes par championnat.</p>
        <h3>6.3 Organisation technique des rencontres</h3>
        <p>
          Dans la mesure du possible, tous les matchs doivent être organisés dans le mode « Compétition » du
          jeu, qui garantit l'application uniforme des paramètres ci-dessus et empêche toute modification par
          les joueurs.
        </p>
        <h3>6.4 Charte du Fair-Play</h3>
        <p>Le GOUZEPE Gaming Club place le respect et l'esprit sportif au-dessus du résultat.</p>
        <ul class="legal-list">
          <li><strong>Respect mutuel :</strong> les insultes, provocations, moqueries ou tout comportement irrespectueux envers un adversaire ou un autre membre sont strictement interdits, en personne, en jeu, ou sur les canaux de communication du Club.</li>
          <li><strong>Interdiction de l'anti-jeu :</strong> sont notamment interdites les pauses excessives ou non justifiées, destinées à casser le rythme de l'adversaire.</li>
          <li><strong>Sanctions pour manque de fair-play :</strong> tout manquement constaté peut entraîner, à la discrétion du Bureau Exécutif : un avertissement officiel, une suspension d'une ou plusieurs journées, la perte du match par pénalité, une amende, voire une exclusion définitive du championnat et/ou du Club dans les cas les plus graves.</li>
        </ul>

        <h2>A7 — Problèmes Techniques et Matériel</h2>
        <h3>7.1 Procédure en cas de déconnexion</h3>
        <p>
          Les déconnexions intempestives (coupure de courant, perte de connexion) sont gérées au cas par cas
          par le Comité d'Organisation, sur la base du score acquis au moment de l'incident et des
          circonstances rapportées par les deux joueurs.
        </p>
        <h3>7.2 Procédure en cas de blocage du jeu ou de la console</h3>
        <p>
          Si le jeu ou la console se bloque, le joueur concerné doit immédiatement mettre le jeu en pause s'il
          le peut, pour éviter que le match ne se poursuive en arrière-plan. La situation est alors traitée
          comme une déconnexion (voir 7.1).
        </p>
        <h3>7.3 Rôle et autorité du Comité d'Organisation</h3>
        <p>
          Un Comité d'Organisation, composé de membres du Bureau Exécutif et de volontaires désignés, est
          responsable du bon déroulement des journées de championnat. Ses prérogatives :
        </p>
        <ul class="legal-list">
          <li>La gestion et la saisie des résultats.</li>
          <li>La collecte et la publication des résultats.</li>
          <li>Le calcul et la publication des classements (journée et général).</li>
          <li>L'application du présent règlement.</li>
          <li>L'arbitrage des litiges en première instance — en cas de désaccord, la décision finale revient au Bureau Exécutif du Club.</li>
        </ul>
        <h3>7.4 Rapport des résultats du championnat</h3>
        <p>
          À la fin de chaque journée, les deux champions (D1 et D2) sont tenus de transmettre les résultats
          finaux (capture d'écran) dans le canal de communication officiel du Club (groupe WhatsApp).
        </p>
        <p>
          <strong>Rapport définitif :</strong> le rapport définitif des résultats doit être transmis au
          maximum 24 heures après la fin du championnat.
        </p>
        <p class="legal-note">NB : en cas de non-respect, une sanction peut être appliquée par le Bureau Exécutif.</p>

        <h2>A8 — Récompenses et Bonus</h2>
        <h3>8.1 Attribution des points bonus hebdomadaires</h3>
        <p>À l'issue de chaque journée, des points bonus s'ajoutent au total du joueur pour le Classement Général :</p>
        <ul class="legal-list">
          <li><strong>Bonus Attaque (+1 point) :</strong> attribué au joueur ayant marqué le plus de buts de la journée, toutes divisions confondues (partagé en cas d'égalité).</li>
          <li><strong>Bonus Défense (+1 point) :</strong> attribué au joueur ayant encaissé le moins de buts de la journée, toutes divisions confondues (partagé en cas d'égalité).</li>
        </ul>
        <p>
          <strong>Condition d'éligibilité :</strong> un joueur doit avoir disputé un minimum de trois (3)
          matchs au cours de la journée pour être éligible à ces bonus.
        </p>
        <h3>8.2 Récompenses spéciales de la saison</h3>
        <ul class="legal-list">
          <li><strong>Joueur du Mois :</strong> des titres honorifiques sont décernés en fin de mois civil, sur la base des points de classement et bonus cumulés sur les journées du mois.</li>
          <li><strong>Match de Gala :</strong> lors de la dernière journée de la saison, un match amical peut être organisé par le Comité d'Organisation.</li>
          <li><strong>Trophée du Spectacle :</strong> récompense le joueur ayant la moyenne de buts la plus élevée (buts marqués + buts encaissés / nombre de matchs joués) sur l'ensemble de la saison.</li>
        </ul>

        <h2>Conclusion générale</h2>
        <p>
          Ce règlement, établi conformément aux statuts et aux valeurs du GOUZEPE Gaming Club, a été conçu
          pour garantir le championnat eFootball de la manière la plus juste, transparente et motivante
          possible.
        </p>
        <p>
          Chaque membre est invité à le lire attentivement et à s'y conformer, car l'excellence sportive se
          mesure autant par le talent que par l'attitude.
        </p>
        <p>
          Le Bureau Exécutif reste souverain pour interpréter, modifier ou amender ce règlement si les
          circonstances l'exigent, pour le bien du Club et de ses membres. Toute modification sera communiquée
          officiellement à l'ensemble des participants.
        </p>

